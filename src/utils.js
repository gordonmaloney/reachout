function getFirstName(contact) {
  return (contact?.name || "").split(" ")[0];
}

function personalizeMessage(contact, template) {
  const body = template?.body || "";
  return body.replace(/\{FIRSTNAME\}/g, getFirstName(contact));
}

function stripWhatsAppFormatting(message) {
  return message.replace(/[*_]/g, "");
}

function digitsOnly(value) {
  return value.replace(/\D/g, "");
}

export function normalizePhoneNumber(phone, dialCode = "+44") {
  const raw = String(phone || "").trim();
  const selectedCodeDigits = digitsOnly(dialCode);
  const knownCodeDigits = dialCodeOptions.map((option) =>
    digitsOnly(option.value)
  );

  if (!raw) return "";

  if (raw.startsWith("+")) {
    return `+${digitsOnly(raw)}`;
  }

  const compact = raw.replace(/[\s().-]/g, "");
  if (compact.startsWith("00")) {
    return `+${digitsOnly(compact.slice(2))}`;
  }

  const phoneDigits = digitsOnly(raw);
  const matchingCode = knownCodeDigits
    .filter(
      (code) =>
        phoneDigits.startsWith(code) &&
        phoneDigits.length > code.length + 5 &&
        (code.length > 1 || phoneDigits.length - code.length >= 10)
    )
    .sort((a, b) => b.length - a.length)[0];

  if (matchingCode) {
    return `+${phoneDigits}`;
  }

  const localDigits = phoneDigits.replace(/^0+/, "");
  return `+${selectedCodeDigits}${localDigits}`;
}

export function getContactDuplicateKey(contact, selectedDialCode = "+44") {
  const rawPhone = String(contact?.phone || "");
  const rawDigits = digitsOnly(rawPhone);
  if (!rawDigits) return "";

  const normalizedPhone = normalizePhoneNumber(rawPhone, selectedDialCode);
  const normalizedDigits = digitsOnly(normalizedPhone);
  const selectedDialDigits = digitsOnly(selectedDialCode);
  const nationalDigits = normalizedDigits.startsWith(selectedDialDigits)
    ? normalizedDigits.slice(selectedDialDigits.length)
    : normalizedDigits;

  // Avoid treating placeholders like "n/a" or "0" as duplicate phone numbers.
  if (nationalDigits.length < 7) return "";

  return normalizedPhone;
}

export function getDuplicateContactIds(contacts, selectedDialCode = "+44") {
  const firstContactByKey = new Map();
  const duplicateIds = new Set();

  contacts.forEach((contact) => {
    const key = getContactDuplicateKey(contact, selectedDialCode);
    if (!key || contact?.id == null) return;

    if (firstContactByKey.has(key)) {
      duplicateIds.add(contact.id);
      return;
    }

    firstContactByKey.set(key, contact.id);
  });

  return duplicateIds;
}

export function removeDuplicateContacts(contacts, selectedDialCode = "+44") {
  const seen = new Set();

  return contacts.filter((contact) => {
    const key = getContactDuplicateKey(contact, selectedDialCode);
    if (!key) return true;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

export function getWhatsAppPhoneNumber(phone, dialCode = "+44") {
  return digitsOnly(normalizePhoneNumber(phone, dialCode));
}

export function getOutboundMessage(
  contact,
  template,
  { plainText = false } = {}
) {
  const message = personalizeMessage(contact, template);
  return plainText ? stripWhatsAppFormatting(message) : message;
}

export function generateWhatsAppLink(contact, template, dialCode = "+44") {
  const base = "https://wa.me/";
  const phone = getWhatsAppPhoneNumber(contact.phone, dialCode);
  const message = personalizeMessage(contact, template).trim();
  if (!message) return `${base}${phone}`;

  const text = encodeURIComponent(message);
  return `${base}${phone}?text=${text}`;
}

export function generateSmsLink(contact, template, dialCode = "+44") {
  const base = "sms:";
  const phone = normalizePhoneNumber(contact.phone, dialCode);
  const message = getOutboundMessage(contact, template, {
    plainText: true,
  }).trim();
  if (!message) return `${base}${phone}`;

  const body = encodeURIComponent(message);
  return `${base}${phone}&body=${body}`;
}

export function generateSignalLink(contact, dialCode = "+44") {
  return `https://signal.me/#p/${encodeURIComponent(
    normalizePhoneNumber(contact.phone, dialCode)
  )}`;
}

export function generateTelegramLink(contact, dialCode = "+44") {
  return `tg://resolve?phone=${digitsOnly(
    normalizePhoneNumber(contact.phone, dialCode)
  )}`;
}

export function generatePreview(contact, template) {
  return personalizeMessage(contact, template);
}

export function generateCallLink(contact, dialCode = "+44") {
  const phone = normalizePhoneNumber(contact.phone, dialCode);
  return `tel:${phone}`;
}
